export function localeOrDefault(value) {
  return LANGUAGES.some(l => l.code === value) ? value : DEFAULT_LANGUAGE;
}
export function directionFor(code) {
  return code === 'fa' || code === 'ar' ? 'rtl' : 'ltr';
}
export function translate(code, key) {
  const dictionary = UI[localeOrDefault(code)];
  return dictionary[key] ?? UI.en[key] ?? key;
}
